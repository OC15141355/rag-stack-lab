#!/usr/bin/env python3
"""The ONE generator: catalogue + templates + vendored charts -> clusters/<env>/ (committed, never hand-edited).

    python3 tools/render.py            write clusters/{dev,qa,prod}/
    python3 tools/render.py --check    render to a temp dir and fail (exit 1) on any difference from clusters/
    python3 tools/render.py --out DIR  write <DIR>/<env>/ instead (used by tests and by --check)

Needs only the Python stdlib, PyYAML and the helm binary at the version pinned in catalogue/platform.yaml
(tools.helm). Charts come ONLY from platform/charts/*.tgz, verified against platform/charts/SHA256SUMS; helm runs
with empty, throwaway config/cache dirs, so it has no repositories and needs no network.

Output per environment:
    00-crds/       CRDs of every helm component that ships them (applied first, server-side)
    10-platform/   namespaces, policies, quota, StorageClass, rendered operator charts (all cluster-scoped objects)
    20-weights/    one PVC + verify Job per (service, weights revision); the verify script ConfigMap
    30-services/   NIMCache + NIMService + NetworkPolicy per LLM; Deployment + Service + NetworkPolicy per other service
    40-gateway/    Bifrost Deployment/Service/policies, its config.json + models.json (ConfigMap), smoke Jobs

Invariants (each also has a CI check in tools/checks.py):
  - deterministic: same inputs, same bytes (sorted objects, sorted keys, no timestamps, no git revision anywhere);
  - every object carries the label managed-by=platform-gitops (the drift job's orphan detection keys on it);
  - pod templates carry content hashes only (config, Secret source files), never a revision or commit: an
    unrelated merge must not roll PROD pods.
Exit: 0 ok, 1 --check found differences, 2 catalogue/template/tool error.
"""
